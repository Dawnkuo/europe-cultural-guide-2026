import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import sharp from 'sharp';

const origin = process.env.QA_ORIGIN ?? 'http://localhost:55910';
const output = process.env.QA_OUTPUT ?? 'work/experience/vatican-library-qa';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const report = [];
const widths = (process.env.QA_WIDTHS ?? '1440,820,390,320').split(',').map(Number);
try {
  for (const width of widths) {
    const page = await browser.newPage({ viewport: { width, height: 960 }, reducedMotion: 'reduce', serviceWorkers: 'block', hasTouch: width <= 390 });
    const errors = [];
    const meshRequests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => { if (r.url().endsWith('st-peters-exterior.glb')) meshRequests.push(r.url()); });
    await page.goto(`${origin}/guides/vatican-museums/`, { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: '馆区总览', exact: true }).click();
    await page.getByLabel('馆区列表').getByRole('button', { name: '图书馆横翼', exact: true }).click();
    const study = page.locator('.vatican-library');
    await study.locator('summary').click();
    const plan = study.getByRole('img');
    await plan.waitFor();
    assert.equal(await plan.count(), 1);
    await plan.scrollIntoViewIfNeeded();
    await study.screenshot({ path: `${output}/plan-${width}.png` });
    assert.equal(await study.getByRole('listitem').count(), 3);
    assert.equal(await study.locator('svg.is-landscape rect').count(), 40);
    await study.getByRole('button', { name: '放大图书馆平面', exact: true }).click();
    assert.notEqual(await study.getByLabel('图书馆平面缩放比例').innerText(), '100%');
    await study.getByRole('button', { name: '重置图书馆平面', exact: true }).click();
    await study.getByRole('application', { name: '图书馆二维剖切' }).focus();
    await page.keyboard.press('+');
    assert.notEqual(await study.getByLabel('图书馆平面缩放比例').innerText(), '100%');
    await page.keyboard.press('Home');
    await study.getByRole('button', { name: '3D 剖切', exact: true }).click();
    const canvas = study.locator('canvas');
    await canvas.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => Number(document.querySelector('.vatican-library canvas')?.dataset.frames) > 0);
    assert.equal(await canvas.getAttribute('data-model'), 'sistine-library-transverse-cutaway');
    assert.equal(meshRequests.length, 0, 'A local library study must not fetch the unrelated basilica mesh');
    const firstCamera = await canvas.getAttribute('data-camera');
    const png = await canvas.screenshot({ path: `${output}/model-${width}.png` });
    const stats = await sharp(png).stats();
    assert.ok(stats.channels[0].stdev > 15, 'Blank library geometry');
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + 60, box.y + box.height / 2 + 20, { steps: 10 });
    await page.mouse.up();
    assert.notEqual(await canvas.getAttribute('data-camera'), firstCamera);
    assert.notDeepEqual(await canvas.screenshot(), png, 'Rotation must change pixels');
    await study.getByRole('button', { name: '显示完整图书馆剖切' }).click();
    await page.waitForFunction(expected => document.querySelector('.vatican-library canvas')?.dataset.camera === expected, firstCamera);
    assert.equal(await canvas.getAttribute('data-camera'), firstCamera);
    await study.getByRole('button', { name: '放大图书馆剖切' }).click();
    await page.waitForFunction(() => Number(document.querySelector('.vatican-library canvas')?.dataset.zoom) > 1);
    assert.ok(Number(await canvas.getAttribute('data-zoom')) > 1);
    const triangles = Number(await canvas.getAttribute('data-triangles'));
    const calls = Number(await canvas.getAttribute('data-draw-calls'));
    await canvas.evaluate(c => { window.__libraryContext = c.getContext('webgl2'); });
    await study.getByRole('button', { name: '2D 平面' }).click();
    assert.equal(await study.getByLabel('图书馆平面缩放比例').innerText(), '100%');
    assert.equal(await page.evaluate(() => window.__libraryContext.isContextLost()), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.deepEqual(errors, []);
    report.push({ width, triangles, calls, rotationPixels: true, zoomReset: true, disposed: true, unrelatedMeshRequests: meshRequests.length, errors });
    console.log(JSON.stringify(report.at(-1)));
    await page.close();
  }
  await writeFile(`${output}/report.json`, JSON.stringify(report, null, 2));
} finally { await browser.close(); }
