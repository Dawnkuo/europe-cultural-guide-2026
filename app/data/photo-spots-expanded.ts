import media from './photo-spot-media.generated.json';
import type { PhotoSpot } from './photo-spots';

type View = Pick<
  PhotoSpot,
  | 'id'
  | 'title'
  | 'kind'
  | 'room'
  | 'position'
  | 'direction'
  | 'composition'
  | 'advice'
  | 'referenceNote'
>;
function view(
  id: PhotoSpot['id'],
  title: string,
  kind: NonNullable<PhotoSpot['kind']>,
  room: string,
  position: string,
  direction: string,
  composition: string,
  advice: string,
  referenceNote = '',
): View {
  return {
    id,
    title,
    kind,
    room,
    position,
    direction,
    composition,
    advice,
    referenceNote,
  };
}
function venue(
  city: string,
  guideSlugs: string[],
  mapQuery: string,
  access: string,
  policyKey: string | undefined,
  views: View[],
): PhotoSpot[] {
  return views.map((item) => ({
    ...item,
    city,
    guideSlugs,
    mapQuery,
    access,
    policyKey,
    shotDate:
      media[item.id].capturedAt.match(/\b\d{4}-\d{2}-\d{2}\b/)?.[0] ??
      '日期未注明',
    referenceNote: `${item.referenceNote ? `${item.referenceNote} ` : ''}站位文字按原图空间关系推定，不是测绘点；展陈、围栏与开放范围可能变化。`,
    alt: `${item.title}实拍：${item.composition}`,
  }));
}

