export function stPetersWorld([x, z]: ExteriorPoint): ExteriorPoint {
  return [
    (x - stPetersPlan.origin[0]) * stPetersPlan.scale,
    (z - stPetersPlan.origin[1]) * stPetersPlan.scale,
  ];
}

